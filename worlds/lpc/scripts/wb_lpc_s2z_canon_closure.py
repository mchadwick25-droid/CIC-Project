def emit_witness(w: dict) -> Path:
    rid = f"lpc.witness.{w['slug']}"
    payload = {
        "id": rid, "world_id": WORLD_ID, "record_type": "doctrinal_witness", "schema_version": SCHEMA_VERSION,
        "status": "draft", "register": "emic", "canon_cells": w["cells"],
        "confidence": w["confidence"], "sources": w["sources"],
        "retrieval": retrieval(2, retrieve_when=w["retrieve_when"]),
        "relations": w["relations"],
        "positions": w["positions"], "tensions": w["tensions"], "text": w["text"],
    }
    return _write("doctrinal_witness", rid, payload, w["body"])


