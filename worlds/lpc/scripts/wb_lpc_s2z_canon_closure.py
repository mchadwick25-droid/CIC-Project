def src(*pairs):
    return [{"source_id": sid, "locus": locus, "license": "public-domain"} for sid, locus in pairs]


def retrieval(tier, retrieve_when=None, do_not=None):
    return {"tier": tier, "retrieve_when": retrieve_when or [], "do_not_retrieve_when": do_not or []}


