const { chromium, devices } = require('playwright');
const out=process.argv[2];
(async()=>{const b=await chromium.launch();
const run=async(name,ctxOpts,fn)=>{const c=await b.newContext(ctxOpts);const p=await c.newPage();const errs=[];p.on('pageerror',e=>errs.push(e.message));
 await p.goto('http://localhost:8765/');await p.waitForTimeout(2500);if(fn)await fn(p);await p.waitForTimeout(600);
 await p.screenshot({path:`${out}/${name}.png`});if(errs.length)console.log(name,'ERR',errs);await c.close();};
const D={viewport:{width:1440,height:900}}, T={...devices['iPad Mini']}, P={...devices['iPhone 13']};
const who=(lane,era)=>async p=>{await p.evaluate(([l,e])=>setWho({type:'river',lane:l,era:e},{on:true}),[lane,era]);};
const zoom=(s,x,y)=>async p=>{await p.evaluate(([s,x,y])=>{scale=s;tx=window.innerWidth/2-x*s;ty=window.innerHeight/2-y*s;applyTransform();applyDetail();},[s,x,y]);};
await run('d-open',D);
await run('d-who-latin2',D,who(5,1));
await run('d-close',D,async p=>{const m=await p.evaluate(()=>{const m=byId['alexandria-catechetical'];return [m._x,m._y];});await zoom(1.4,m[0]+150,m[1]+120)(p);});
await run('d-people',D,async p=>{const m=await p.evaluate(()=>{const m=byId['cappadocian-nicene-pastoral-monastic-tradition'];return [m._x,m._y];});await zoom(3.6,m[0]+150,m[1]+60)(p);});
await run('d-key',D,async p=>{await p.click('[aria-controls="sw-key"]');});
await run('d-rivers',D,async p=>{await p.click('[aria-controls="sw-rivers"]');});
await run('d-links',D,async p=>{await p.click('[aria-controls="sw-links"]');await p.click('[data-mode="major"]');});
await run('d-card',D,async p=>{await p.evaluate(()=>openPanel(byId['alexandria-catechetical']));});
await run('d-era',D,async p=>{await p.evaluate(()=>openEraCard(1));});
await run('t-open',T);
await run('t-who',T,who(3,1));
await run('p-open',P);
await run('p-who',P,who(3,1));
await run('p-card',P,async p=>{await p.evaluate(()=>openPanel(byId['alexandria-catechetical']));});
await run('p-conn',P,async p=>{await p.evaluate(()=>showConnections(byId['alexandria-catechetical']));});
await run('p-menu',P,async p=>{await p.click('#menuBtn');});
await b.close();})();
