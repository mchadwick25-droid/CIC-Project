#!/usr/bin/env python3
"""Generates DOWNLOAD-QUEUE.md - one list to work from, not three.

WHY. Before this, "what should I go download" meant checking three places
that overlap but don't agree: Build/Ministry/Technology/table_phase0/
Texts_Acquisition_Wantlist.md (hand-written narrative), each world's own
*_Source_Acquisition_Manifest.md (per-world, prose, hand-written), and
WANTS-REGISTER.md's own "acquirable, public domain" section (generated,
but reactive - it only surfaces a want after some world's build already
cited something unreadable, so a candidate nobody has cited yet stays
invisible to it, per that register's own documented limitation).

WHAT THIS DOES NOT REPLACE. Per-world manifests stay the authoritative
acquisition-priority record for THAT world's own build - this queue is a
cross-world mechanical union of what's confirmed ready to fetch, not a
substitute for a world's own prioritization. search_record entries stay
each world's own auditable reasoning trail. This is a shopping list, not
a decision-maker.

TWO SOURCES, MERGED:
  1. download-queue-seed.yaml (hand-verified, proactive - found by
     searching, not by a record already citing something unreadable)
  2. WANTS-REGISTER.md's own "acquirable, public domain" bucket (generated
     from records/, reactive) - pulled via gen_wants_register.gather_rows()
     rather than scraped from that module's own rendered markdown table,
     the same "don't re-derive what already exists as data" choice
     corpus_index.py made reusing corpus_structure.py's parsing.

Usage:
  python Build/worlds/_cross-world/gen_download_queue.py
"""
from __future__ import annotations

import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import gen_wants_register as wants  # noqa: E402

import yaml

SEED_FILE = HERE / "download-queue-seed.yaml"
TARGET = HERE / "DOWNLOAD-QUEUE.md"


def load_seed() -> list[dict]:
    data = yaml.safe_load(SEED_FILE.read_text(encoding="utf-8")) or {}
    return [q for q in (data.get("queue") or []) if q.get("status") == "not-yet-downloaded"]


def reactive_candidates() -> list[dict]:
    """WANTS-REGISTER's own acquirable-public-domain rows, reshaped to this
    queue's own row shape - same underlying data that module renders,
    fetched as data rather than re-parsed from markdown."""
    rows, _worlds = wants.gather_rows()
    out = []
    for r in rows:
        if r["kind"] != "acquirable, public domain":
            continue
        out.append({
            "title": r["work"] or "(untitled)",
            "author": r["author"] or "—",
            "translator": None,
            "year": None,
            "world": r["world"],
            "why": f"Cited by {r['depends']} record(s) with no vendored edition "
                   f"(source record `{r['id']}`), classified acquirable-public-domain "
                   f"by gen_wants_register.py's own scan of records/.",
            "url": None,
            "rights_basis": None,
            "verified_by": None,
            "source": "reactive",
        })
    return out


def render() -> str:
    seed = [dict(q, source="proactive") for q in load_seed()]
    reactive = reactive_candidates()
    all_rows = seed + reactive

    out = [
        "# Download queue — everything confirmed ready to fetch, in one list\n",
        "Generated by `gen_download_queue.py`, merging two sources: "
        "`download-queue-seed.yaml` (hand-verified candidates found by searching, "
        "before any world's record cited them) and `WANTS-REGISTER.md`'s own "
        "\"acquirable, public domain\" bucket (reactive — surfaced only after a "
        "world's build already cited something unreadable). Per-world "
        "`*_Source_Acquisition_Manifest.md` files remain the authoritative "
        "acquisition-priority record for that world's own build; this is the "
        "cross-world mechanical union, not a replacement.\n",
        f"\n**{len(all_rows)} candidate(s)**: {len(seed)} proactively verified, "
        f"{len(reactive)} surfaced reactively by the wants register.\n",
    ]

    if seed:
        out.append("\n## Proactively verified — url and rights basis confirmed\n")
        out.append("| title | translator (year) | world | url | rights basis | verified by |")
        out.append("|---|---|---|---|---|---|")
        for q in seed:
            translator_year = f"{q.get('translator') or '—'} ({q.get('year') or '?'})"
            out.append(f"| {q['title']} | {translator_year} | `{q['world']}` | "
                       f"{q.get('url') or '—'} | {q.get('rights_basis') or '—'} | "
                       f"{q.get('verified_by') or '—'} |")

    if reactive:
        out.append("\n## Surfaced by the wants register — edition exists, not yet located/verified\n")
        out.append(
            "These are known to be acquirable in principle (a world's own source "
            "record says so), but — unlike the proactive rows above — **no specific "
            "URL has been verified for them yet.** Verifying one and moving it to "
            "`download-queue-seed.yaml` with a real url and rights_basis is exactly "
            "how a row moves from this section to the one above.\n"
        )
        out.append("| title | author | world | why |")
        out.append("|---|---|---|---|")
        for q in reactive:
            out.append(f"| {q['title']} | {q['author']} | `{q['world']}` | {q['why']} |")

    out.append(
        "\n---\n\n## Adding to this queue\n\n"
        "**Proactive finds** (searched for and verified before any record cites "
        "them): add a row to `download-queue-seed.yaml` directly, with a real url "
        "and a rights_basis actually checked against the host — never guessed. "
        "**Reactive wants** need no action here at all: they come from "
        "`WANTS-REGISTER.md`, which is itself generated from records/ every run.\n\n"
        "After downloading and vendoring an item from this queue, move its "
        "seed-file row's `status` to `downloaded` rather than deleting it — the "
        "row is now a record of what was already found and why, the same "
        "no-rewrite-history discipline `cic/engine/texts_registry.py` follows for "
        "its own ENTRIES.\n"
    )
    return "\n".join(out) + "\n"


def main() -> int:
    text = render()
    TARGET.write_text(text, encoding="utf-8")
    print(f"wrote {TARGET}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
