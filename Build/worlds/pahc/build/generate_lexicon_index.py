#!/usr/bin/env python3
"""Regenerate Build/worlds/pahc/build/LEXICON-INDEX.md from records/pahc/term/*.md.

Usage: python3 Build/worlds/pahc/build/generate_lexicon_index.py
Run from the repo root. Writes LEXICON-INDEX.md alongside this script.
"""
import pathlib
import sys

REPO_ROOT = pathlib.Path(__file__).resolve().parents[4]
sys.path.insert(0, str(REPO_ROOT))

from engine.m1.loader import load_world_records
from engine.m1.schemas import RELATION_INVERSE


def risk(r):
    srcs = {s["source_id"] for s in r.get("sources") or []}
    if len(srcs) == 1:
        return "YES (" + next(iter(srcs)).replace("pahc.source.", "") + ")"
    return f"no ({len(srcs)} sources)"


def main():
    recs = load_world_records("pahc")
    terms = {k: v for k, v in recs.items() if v["record_type"] == "term"}

    lines = [
        "# pahc Interpretive Lexicon — Master Index",
        "",
        "**GENERATED from records/pahc/term/ — do not hand-edit.** Regenerate with "
        "`python3 Build/worlds/pahc/build/generate_lexicon_index.py` after any term change. "
        "This index exists so tier, cell, risk, and relation questions are answerable "
        "without opening every record (the cic-lexicon-index discipline). The per-term "
        "structure lives in the records themselves; this is the queryable view.",
        "",
        "## Master table",
        "",
        "| id | world_word | tier | canon_cells | formation_confidence | evidentiary_weight | single-source risk | relations |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for rid in sorted(terms, key=lambda k: (terms[k]["retrieval"]["tier"], k)):
        r = terms[rid]
        rel = "; ".join(
            f"{x['type']}→{x['target'].replace('pahc.term.', '')}" for x in r.get("relations") or []
        )
        lines.append(
            f"| {rid} | {r['world_word']} | {r['retrieval']['tier']} | {', '.join(r['canon_cells'])} "
            f"| {r['confidence']['formation_confidence']} | {r['confidence']['evidentiary_weight']} "
            f"| {risk(r)} | {rel} |"
        )

    lines += ["", "## By tier", ""]
    for t in (1, 2, 3):
        lines.append(
            f"- **Tier {t}:** "
            + ", ".join(sorted(r["world_word"] for r in terms.values() if r["retrieval"]["tier"] == t))
        )

    lines += ["", "## Contested / single-source watch list", ""]
    for rid in sorted(terms):
        r = terms[rid]
        flags = []
        if r["confidence"]["formation_confidence"] in ("Contested", "Inferential-Thin"):
            flags.append(r["confidence"]["formation_confidence"])
        if len({s["source_id"] for s in r.get("sources") or []}) == 1:
            flags.append("single-source")
        if flags:
            lines.append(f"- {rid}: {', '.join(flags)}")

    lines += ["", "## Relation reciprocity check (mechanical)", ""]
    bad = []
    for rid, r in terms.items():
        for rel in r.get("relations") or []:
            tgt = rel["target"]
            inv = RELATION_INVERSE[rel["type"]]
            if tgt in terms:
                back = any(
                    x["type"] == inv and x["target"] == rid for x in terms[tgt].get("relations") or []
                )
                if not back:
                    bad.append((rid, rel["type"], tgt))
    lines.append(
        "All term-to-term relations reciprocate. (Verified by this generator against "
        "RELATION_INVERSE; the M1 reciprocity gate re-verifies on every build run.)"
        if not bad
        else "NON-RECIPROCAL: " + str(bad)
    )

    lines += ["", "---", f"<!-- generated by {pathlib.Path(__file__).name} -->", ""]

    out = pathlib.Path(__file__).resolve().parent / "LEXICON-INDEX.md"
    out.write_text("\n".join(lines))
    print(f"wrote {out} | terms: {len(terms)} | non-reciprocal: {len(bad)}")


if __name__ == "__main__":
    main()
