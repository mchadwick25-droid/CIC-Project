def _yaml_dump(payload: dict) -> str:
    return yaml.safe_dump(payload, sort_keys=False, allow_unicode=True, width=100, default_flow_style=False)


def _write(record_type: str, rid: str, payload: dict, body: str) -> Path:
    path = OUT_ROOT / record_type / f"{rid}.md"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("---\n" + _yaml_dump(payload) + "---\n" + body.strip() + "\n", encoding="utf-8")
    return path


def conf(cite, verify, weight, formation, divergence=None):
    return {
        "citation_specificity": cite,
        "verification_state": verify,
        "evidentiary_weight": weight,
        "formation_confidence": formation,
        "divergence_note": divergence,
    }


def src(*pairs):
    return [{"source_id": sid, "locus": locus, "license": "public-domain"} for sid, locus in pairs]


def retrieval(tier, retrieve_when=None, do_not=None):
    return {"tier": tier, "retrieve_when": retrieve_when or [], "do_not_retrieve_when": do_not or []}


