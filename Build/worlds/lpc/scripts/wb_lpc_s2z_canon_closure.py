def emit_limit(lm: dict) -> Path:
    rid = f"lpc.limit.{lm['slug']}"
    payload = {
        "id": rid, "world_id": WORLD_ID, "record_type": "honest_limit", "schema_version": SCHEMA_VERSION,
        "status": "draft", "register": "emic", "canon_cells": lm["cells"],
        "confidence": lm["confidence"], "sources": lm["sources"], "relations": lm["relations"],
        "statement": lm["statement"], "why_sources_cannot_answer": lm["why_sources_cannot_answer"],
        "nearest_material": lm["nearest_material"],
    }
    return _write("honest_limit", rid, payload, lm["body"])


def _print_disposition(records: dict, fleet: dict) -> None:
    sys.path.insert(0, str(REPO_ROOT))
    from engine.m1 import canon

    cells = sorted(canon.valid_cells(fleet))
    print(f"\n{len(cells)} valid cells confirmed against the fleet's own canon_question records.")
    counts = {"substantive": 0, "honest_limit": 0, "empty": 0, "multiple_honest_limit": 0}
    for cell in cells:
        classification = canon.classify_cell(cell, records)
        counts[classification["status"]] += 1
        detail = ""
        if classification["status"] == "substantive":
            detail = f" <- {', '.join(classification['substantive'])}"
        elif classification["status"] in ("honest_limit", "multiple_honest_limit"):
            detail = f" <- {', '.join(classification['honest_limit'])}"
        print(f"  {cell:6s} {classification['status']}{detail}")
    print(f"\nTotals: {counts}")


def main() -> int:
    if "--validate" not in sys.argv:
        print(
            "This script's own write path is retired: WITNESSES/LIMITS below are stale build\n"
            "history, not a source of truth to regenerate from. The records at records/lpc/\n"
            "{doctrinal_witness,honest_limit}/ are hand-maintained since the independent fidelity\n"
            "review logged as OG-14/OG-15 (Build/worlds/lpc/Open_Gaps_Tracking.md) -- re-running the old\n"
            "write path would silently overwrite corrected records with the pre-review text,\n"
            "including recreating honest_limit records the review found fully answered and retired.\n"
            "Run with --validate to check the real records against the gate battery instead."
        )
        return 1

    sys.path.insert(0, str(REPO_ROOT))
    from engine.m1 import gates
    from engine.m1.loader import load_fleet_records, load_world_records
    from engine.m1.registry import load_registry  # type: ignore

    records = load_world_records("lpc")
    fleet = load_fleet_records()
    registry = load_registry()
    print("Running gate battery against the real lpc + fleet corpus...")
    results = gates.run_all(records, fleet, registry)
    any_findings = False
    for name, findings in results.items():
        if findings:
            any_findings = True
            print(f"\n=== {name}: {len(findings)} finding(s) ===")
            for f in findings:
                print(f"  - {f}")
        else:
            print(f"{name}: clean")
    _print_disposition(records, fleet)
    if any_findings:
        print("\nSome gates report findings -- see above.")
        return 1
    print("\nAll gates clean.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
